//! RaptorQ decodes off the tee (4k-repair).
//!
//! A part of several symbols is assembled by its tee's receiver itself
//! (`RelayObjectReceiver::set_defer_decode`): whole from its source symbols
//! it is their bytes, with no RaptorQ at all; short of them, its decode is a
//! `DecodeJob` that the tee hands to this pool, so that a 6 MB part's 30 ms
//! solve never holds the tee (and the parts behind it) back. The result
//! comes back to the submitting tee on its channel, and the tee commits the
//! part as it would have inline. Parts complete in the order their decodes
//! do: a part whose decode is under way does not hold later parts, whole
//! from their sources, from being committed (the cache takes parts out of
//! order; its watermark waits for a hole up to the repair horizon, as for a
//! part the cache mesh fills).
//!
//! The workers: at most `--relay-decode-workers` (by default the node's
//! CPUs less the two class threads, at least 1, at most 4), unpinned, at the
//! tee's nice value (+10): below the class threads (FIFO 10 and nice -10)
//! and the edge's fan-out threads, so a decode takes only what they leave.
//! A full queue (`DECODE_QUEUE`) sends the job back to the tee, which runs
//! it inline (`inline` counts them).

use super::part_repair::PartMeta;
use av_mesh::mem_guard::{Shed, StoreAccount, StoreKind};
use av_mesh::relay_ingress::DecodeJob;
use serde::Serialize;
use std::collections::VecDeque;
use std::net::SocketAddr;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Arc, Condvar, Mutex};
use std::time::Instant;
use tokio::sync::mpsc::UnboundedSender;
use tracing::{info, warn};

/// Decodes waiting at most; past it a tee decodes inline.
pub const DECODE_QUEUE: usize = 32;
/// The bytes the queue and its results not yet taken back may hold by
/// default (`--relay-decode-queue-mb`); past it a tee decodes inline. Each
/// job is counted twice (its symbols, and the envelope its decode makes)
/// from its submission until its tee takes the result: 64 MiB is about 24
/// parts of 4K at 247 Mbit/s, or 5 key frames of 6 MB.
pub const DECODE_QUEUE_BYTES: usize = 64 << 20;
/// The workers' nice value: the tee's.
pub const DECODE_NICE: i32 = 10;

/// What the tee knew of the symbol that made a decode ready.
#[derive(Debug, Clone)]
pub struct DecodedCtx {
    pub peer: SocketAddr,
    pub rx_us: u64,
    pub woken_us: u64,
    pub forwarded: Option<(SocketAddr, u64)>,
    pub video_kind: bool,
    pub meta: Option<PartMeta>,
    /// The part's source symbols this node lacked (regenerated by the
    /// decode).
    pub missing: Vec<u32>,
}

/// A finished decode, back to its tee.
pub struct DecodeDone {
    pub job: DecodeJob,
    pub ctx: DecodedCtx,
    pub envelope: Option<Vec<u8>>,
    /// What the job counts in the pool's account (0 for an inline decode):
    /// given back by [`DecodePool::taken`] when its tee takes it.
    pub bytes: u64,
}

struct Task {
    job: DecodeJob,
    ctx: DecodedCtx,
    done: UnboundedSender<DecodeDone>,
    bytes: u64,
}

#[derive(Debug, Default)]
pub struct DecodePoolStats {
    pub decodes: AtomicU64,
    pub failures: AtomicU64,
    pub decode_us: AtomicU64,
    pub decode_us_max: AtomicU64,
    pub inline: AtomicU64,
    pub queued_max: AtomicU64,
    /// Decodes run inline because the queue's bytes were at their limit
    /// (in `inline` too).
    pub inline_bytes_limited: AtomicU64,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, serde::Deserialize)]
#[serde(default)]
pub struct DecodePoolSnapshot {
    pub workers: u64,
    pub decodes: u64,
    pub failures: u64,
    pub decode_us: u64,
    pub decode_us_max: u64,
    pub inline: u64,
    pub queued_max: u64,
    pub inline_bytes_limited: u64,
    pub queue_bytes: u64,
    pub queue_budget_bytes: u64,
}

struct Shared {
    queue: Mutex<VecDeque<Task>>,
    ready: Condvar,
    stop: AtomicBool,
}

pub struct DecodePool {
    shared: Arc<Shared>,
    workers: usize,
    pub stats: Arc<DecodePoolStats>,
    /// The queue's bytes and its results' in the memory guard's account.
    account: Arc<StoreAccount>,
}

impl Shed for DecodePool {
    fn account(&self) -> &StoreAccount {
        &self.account
    }

    /// Nothing is dropped: a queued decode is a part. Its limit only sends
    /// new decodes back to their tees, inline, until the queue drains.
    fn shed_to_limit(&self) -> u64 {
        0
    }
}

impl std::fmt::Debug for DecodePool {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("DecodePool")
            .field("workers", &self.workers)
            .finish_non_exhaustive()
    }
}

/// The default worker count: the node's CPUs less the two class threads,
/// at least 1, at most 4.
pub fn default_workers() -> usize {
    std::thread::available_parallelism()
        .map_or(2, std::num::NonZeroUsize::get)
        .saturating_sub(2)
        .clamp(1, 4)
}

impl DecodePool {
    /// `None` for no workers (the tees decode inline). `queue_bytes`: the
    /// bytes the queue and its untaken results may hold.
    pub fn start(workers: usize, queue_bytes: usize) -> Option<Arc<Self>> {
        if workers == 0 {
            return None;
        }
        let shared = Arc::new(Shared {
            queue: Mutex::new(VecDeque::with_capacity(DECODE_QUEUE)),
            ready: Condvar::new(),
            stop: AtomicBool::new(false),
        });
        let stats = Arc::new(DecodePoolStats::default());
        let account = Arc::new(StoreAccount::new(StoreKind::DecodeQueue, queue_bytes as u64));
        let mut started = 0;
        for index in 0..workers {
            let (shared, stats, account) =
                (Arc::clone(&shared), Arc::clone(&stats), Arc::clone(&account));
            match std::thread::Builder::new()
                .name(format!("needletail-decode-{index}"))
                .spawn(move || run_worker(&shared, &stats, &account))
            {
                Ok(_) => started += 1,
                Err(error) => warn!(error = %error, "a decode worker did not start"),
            }
        }
        info!(workers = started, "RaptorQ decodes run off the tees");
        (started > 0).then(|| {
            let pool = Arc::new(Self {
                shared,
                workers: started,
                stats,
                account,
            });
            let weak: std::sync::Weak<dyn Shed> = Arc::downgrade(&pool) as _;
            av_mesh::mem_guard::register_store(weak);
            pool
        })
    }

    /// Queue a decode; the job comes back when the queue is full.
    pub fn submit(
        &self,
        job: DecodeJob,
        ctx: DecodedCtx,
        done: &UnboundedSender<DecodeDone>,
    ) -> Result<(), (DecodeJob, DecodedCtx)> {
        let bytes = 2 * job.bytes() as u64;
        if self.account.held() + bytes > self.account.limit() {
            self.stats.inline.fetch_add(1, Ordering::Relaxed);
            self.stats.inline_bytes_limited.fetch_add(1, Ordering::Relaxed);
            return Err((job, ctx));
        }
        let mut queue = self.shared.queue.lock().unwrap_or_else(|e| e.into_inner());
        if queue.len() >= DECODE_QUEUE {
            self.stats.inline.fetch_add(1, Ordering::Relaxed);
            return Err((job, ctx));
        }
        self.account.add(bytes);
        queue.push_back(Task {
            job,
            ctx,
            done: done.clone(),
            bytes,
        });
        self.stats
            .queued_max
            .fetch_max(queue.len() as u64, Ordering::Relaxed);
        drop(queue);
        self.shared.ready.notify_one();
        Ok(())
    }

    /// A tee took a result back: its bytes leave the account.
    pub fn taken(&self, bytes: u64) {
        self.account.sub(bytes);
    }

    pub fn snapshot(&self) -> DecodePoolSnapshot {
        let load = |value: &AtomicU64| value.load(Ordering::Relaxed);
        DecodePoolSnapshot {
            workers: self.workers as u64,
            decodes: load(&self.stats.decodes),
            failures: load(&self.stats.failures),
            decode_us: load(&self.stats.decode_us),
            decode_us_max: load(&self.stats.decode_us_max),
            inline: load(&self.stats.inline),
            queued_max: load(&self.stats.queued_max),
            inline_bytes_limited: load(&self.stats.inline_bytes_limited),
            queue_bytes: self.account.held(),
            queue_budget_bytes: self.account.budget(),
        }
    }
}

impl Drop for DecodePool {
    fn drop(&mut self) {
        self.shared.stop.store(true, Ordering::Relaxed);
        self.shared.ready.notify_all();
    }
}

/// Run one decode, counting it.
pub fn decode(job: &DecodeJob, stats: &DecodePoolStats) -> Option<Vec<u8>> {
    let started = Instant::now();
    let envelope = job.run();
    let took = started.elapsed().as_micros() as u64;
    stats.decodes.fetch_add(1, Ordering::Relaxed);
    stats.decode_us.fetch_add(took, Ordering::Relaxed);
    stats.decode_us_max.fetch_max(took, Ordering::Relaxed);
    if envelope.is_none() {
        stats.failures.fetch_add(1, Ordering::Relaxed);
    }
    envelope
}

fn run_worker(shared: &Shared, stats: &DecodePoolStats, account: &StoreAccount) {
    let _ = super::sys::set_nice(DECODE_NICE);
    loop {
        let task = {
            let mut queue = shared.queue.lock().unwrap_or_else(|e| e.into_inner());
            loop {
                if shared.stop.load(Ordering::Relaxed) {
                    return;
                }
                if let Some(task) = queue.pop_front() {
                    break task;
                }
                queue = shared.ready.wait(queue).unwrap_or_else(|e| e.into_inner());
            }
        };
        let envelope = decode(&task.job, stats);
        if let Err(lost) = task.done.send(DecodeDone {
            job: task.job,
            ctx: task.ctx,
            envelope,
            bytes: task.bytes,
        }) {
            // Its tee is gone: nobody gives the bytes back but here.
            drop(lost);
            account.sub(task.bytes);
        }
    }
}
